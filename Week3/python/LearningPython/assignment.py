# Assignment Operators

# There are many different assignment operators, primarily for numeric operations.
# See list below:

#       Operator	Example	        Same As
#       =	        x = 5	        x = 5	
#       +=	        x += 3	        x = x + 3	
#       -=	        x -= 3	        x = x - 3	
#       *=	        x *= 3	        x = x * 3	
#       /=	        x /= 3	        x = x / 3	
#       %=	        x %= 3	        x = x % 3	
#       //=	        x //= 3	        x = x // 3	
#       **=	        x**= 3	        x = x ** 3	


# There are more operators than those listed above, although those are some of the most commonly used. 
# Know that more exist, such as the bitwise operators below, but you can and should ignore them for now. 
# They won't be relevant for this course, but you may encounter them in the wild at some point. 

#       Operator	Example	        Same As
#       &=	        x &= 3	        x = x & 3	
#       |=	        x |= 3	        x = x | 3	
#       ^=	        x ^= 3	        x = x ^ 3	
#       >>=	        x >>= 3	        x = x >> 3	
#       <<=	        x <<= 3	        x = x << 3	
#       :=	        print(x := 3)	x = 3 print(x)